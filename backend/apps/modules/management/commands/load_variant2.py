    def _create_steps(self, module, steps_data):
        for row in steps_data:
            number, title, description, expected_result, note_type, note_title, note_content = row
            step, _ = ModuleStep.objects.update_or_create(
                module=module,
                number=number,
                defaults={
                    'title': title,
                    'description': description,
                    'expected_result': expected_result or '',
                    'order': number,
                }
            )
            if note_type and note_content:
                StepNote.objects.update_or_create(
                    step=step,
                    title=note_title or '',
                    defaults={
                        'note_type': note_type,
                        'content': note_content,
                        'order': 1,
                    }
                )

    def _create_criteria(self, module, criteria):
        for order, (name, description, score) in enumerate(criteria, start=1):
            EvaluationCriteria.objects.update_or_create(
                module=module,
                name=name,
                defaults={
                    'description': description,
                    'max_score': score,
                    'order': order,
                }
            )
